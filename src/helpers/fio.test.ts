import { describe, expect, it } from 'vitest'
import { toKey, toShow } from './fio'

// Характеризационные тесты: фиксируют текущее поведение хелперов ФИО.

const NBSP = String.fromCharCode(0xa0)

describe('toShow', () => {
  it('заменяет строчную ё на е и схлопывает подряд идущие пробелы', () => {
    expect(toShow('Сёмин   Пётр  Алексеевич')).toBe('Семин Петр Алексеевич')
  })

  it('сохраняет регистр, заглавную Ё и крайние пробелы', () => {
    expect(toShow(' Ёлкин Иван ')).toBe(' Ёлкин Иван ')
  })
})

describe('toKey', () => {
  it('даёт одинаковый ключ для написаний, отличающихся регистром, ё/е и пробелами', () => {
    expect(toKey('  Ёлкин   Пётр ')).toBe('елкин петр')
    expect(toKey('ЕЛКИН ПЕТР')).toBe('елкин петр')
  })

  it('не заменяет таб и NBSP обычным пробелом и не схлопывает их', () => {
    expect(toKey(`Иванов${NBSP}${NBSP}Иван\t\tИванович`)).toBe(`иванов${NBSP}${NBSP}иван\t\tиванович`)
  })
})
